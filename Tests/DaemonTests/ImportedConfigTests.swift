/// The JSON tools: lists run in turn and stop at the first that fails; comments and trailing commas are read.
@Test func otherToolsFilesBecomeTheProjectsCommands() {
    let cursor = ImportedConfig.cursor(#"{"setup-worktree": ["npm ci"], "setup-worktree-unix": ["pnpm install", "pnpm build"]}"#, "/r")
    #expect(cursor?.setup == "set -e\npnpm install\npnpm build")
    #expect(ImportedConfig.cursor(#"{"setup-worktree": "setup.sh"}"#, "/r")?.setup == "bash '/r/.cursor/setup.sh'")

    let superset = ImportedConfig.superset(#"{"setup": ["pnpm install"], "teardown": [], "run": ["pnpm dev"]}"#, "/r")
    #expect(superset?.setup == "pnpm install" && script(superset, "run") == "pnpm dev" && script(superset, "archive") == nil)

    let emdash = ImportedConfig.emdash(#"{"scripts": {"prepare": "corepack enable", "setup": "pnpm i", "run": "", "teardown": "make clean"}}"#, "/r")
    #expect(emdash?.setup == "set -e\ncorepack enable\npnpm i" && script(emdash, "run") == nil && script(emdash, "archive") == "make clean")

    let air = ImportedConfig.air("""
    {
      // Air's worktree steps
      "setup": { "macos": ["brew install jq", "npm ci"], "windows": ["choco install jq"], },
      "cleanup": { "macos": ["rm -rf node_modules"] },
    }
    """, "/r")
    #expect(air?.setup == "set -e\nbrew install jq\nnpm ci" && script(air, "archive") == "rm -rf node_modules")

    let supacode = ImportedConfig.supacode(#"""
    {"setupScript": "bun i", "deleteScript": "bun clean", "scripts": [
      {"id": "A", "kind": "test", "name": "Tests", "command": "bun test"},
      {"id": "B", "kind": "deploy", "name": "Deploy", "command": "bun deploy"}]}
    """#, "/r")
    #expect(supacode?.setup == "bun i" && script(supacode, "test") == "bun test" && script(supacode, "Deploy") == "bun deploy")
    #expect(script(supacode, "archive") == "bun clean")

    let cmux = ImportedConfig.cmux(#"{"commands": [{"name": "Setup", "command": "make deps"}, {"name": "Format", "command": "prettier -w ."}]}"#, "/r")
    #expect(cmux?.setup == "make deps" && script(cmux, "Format") == "prettier -w .")
}

/// A .kelp.yaml wins over another tool's file; between one tool's files the current one wins; a file that names nothing
/// is passed over for the next.
@Test func theProjectsOwnFileWinsOverAnotherTools() throws {
    let root = FileManager.default.temporaryDirectory.appendingPathComponent("imported-\(UUID().uuidString)").path
    defer { _ = Log.session.attempt("removing the test folder") { try FileManager.default.removeItem(atPath: root) } }
    func write(_ file: String, _ text: String) throws {
        let u = URL(fileURLWithPath: root + "/" + file)
        try FileManager.default.createDirectory(at: u.deletingLastPathComponent(), withIntermediateDirectories: true)
        try text.write(to: u, atomically: true, encoding: .utf8)
    }
    try write(".cursor/worktrees.json", "{}")
    try write("conductor.json", #"{"scripts": {"setup": "old"}}"#)
    #expect(Workspaces.configFile(root).path == root + "/conductor.json", "Cursor's names nothing: the next one's read")
    try write(".conductor/settings.toml", "[scripts]\nsetup = \"new\"\n")
    #expect(Workspaces.configFile(root).config.setup == "new")
    try write(".kelp.yaml", "setup: mine\n")
    let own = Workspaces.configFile(root)
    #expect(own.path == root + "/.kelp.yaml" && own.config.setup == "mine" && own.config.prelude.isEmpty)
}

/// An imported script finds its tool's variables, set from Kelp's own.
@Test func importedScriptsGetTheirToolsVariables() throws {
    let c = try #require(ImportedConfig.conductorJSON(#"{"scripts": {"run": "x"}}"#, "/Users/me/my app"))
    let p = Process()
    p.executableURL = URL(fileURLWithPath: "/bin/zsh")
    p.arguments = ["-c", c.shell(#"echo "$CONDUCTOR_ROOT_PATH|$CONDUCTOR_PORT|$CONDUCTOR_WORKSPACE_NAME""#)]
    p.currentDirectoryURL = FileManager.default.temporaryDirectory
    p.environment = ["KELP_PORT": "4100"]
    let out = Pipe()
    p.standardOutput = out
    try p.run()
    p.waitUntilExit()
    let line = String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
    #expect(line.hasPrefix("/Users/me/my app|4100|"), "\(line)")
}

/// TOML pieces the tools write: arrays over lines, comments after values, escapes, a `#` inside a string.
@Test func miniTOMLReadsWhatTheseFilesUse() {
    let t = MiniTOML("""
    [a]
    list = [
      "one", # first
      'two#2',
    ]
    s = "tab\\there \\"q\\"" # comment
    on = true
    """)
    #expect(t.strings("a.list") == ["one", "two#2"])
    #expect(t.string("a.s") == "tab\there \"q\"")
    #expect(t.bool("a.on"))
}

/// VS Code's and Zed's tasks in the Run menu: plain commands with their args and folder, macOS variants, test groups;
/// left out what only the editor runs (npm tasks are package.json's, `${file}` and `$ZED_FILE` need an open file).
@Test func editorTasksAreOfferedToRun() {
    let vscode = """
    {
      // comments, as VS Code writes them
      "version": "2.0.0",
      "tasks": [
        { "label": "Build", "type": "shell", "command": "make", "args": ["-j8"], "group": { "kind": "build", "isDefault": true } },
        { "label": "Unit", "command": "swift test", "group": "test", "osx": { "command": "swift test --parallel" } },
        { "label": "Script", "type": "process", "command": "${workspaceFolder}/scripts/go.sh", "options": { "cwd": "${workspaceFolder}/app" } },
        { "label": "This file", "type": "shell", "command": "node ${file}" },
        { "label": "dev", "type": "npm", "script": "dev" },
      ]
    }
    """
    let zed = #"""
    [
      { "label": "Serve", "command": "bin/rails", "args": ["s"], "env": { "RAILS_ENV": "development" }, "cwd": "$ZED_WORKTREE_ROOT" },
      { "label": "Run file", "command": "ruby $ZED_FILE" }
    ]
    """#
    let out = "\u{1E}./.vscode/tasks.json\u{1F}\(vscode)\u{1E}./.zed/tasks.json\u{1F}\(zed)\u{1D}"
    let by = Dictionary(Runnables.options(Runnables.parse(out)).map { ($0.name, $0) }) { a, _ in a }
    #expect(by["Build"]?.command == "make '-j8'" && by["Build"]?.kind == "build" && by["Build"]?.folder == "")
    #expect(by["Unit"]?.command == "swift test --parallel" && by["Unit"]?.kind == "test")
    #expect(by["Script"]?.command == "cd './app' && ./scripts/go.sh")
    #expect(by["This file"] == nil && by["dev"] == nil && by["Run file"] == nil)
    #expect(by["Serve"]?.command == "RAILS_ENV='development' bin/rails 's'" && by["Serve"]?.source == ".zed/tasks.json")
}

/// From the daemon's side: a project with only Conductor's file asks for trust naming that file, then a new worktree's
/// setup runs with Conductor's variables (the main checkout, the port Kelp gave the worktree).
@Test func aConductorProjectsSetupRunsOnceTrusted() async throws {
    let (d, c, _) = try daemon(); defer { d.stop() }
    let repoPath = try makeRepo()
    try FileManager.default.removeItem(atPath: repoPath + "/.kelp.yaml")
    try FileManager.default.createDirectory(atPath: repoPath + "/.conductor", withIntermediateDirectories: true)
    try "[scripts]\nsetup = 'echo \"$CONDUCTOR_ROOT_PATH|$CONDUCTOR_PORT\" > SETUP_RAN'\n"
        .write(toFile: repoPath + "/.conductor/settings.toml", atomically: true, encoding: .utf8)
    try Git.run(["add", "-A"], cwd: repoPath)
    try Git.run(["commit", "-qm", "conductor"], cwd: repoPath)

    let repo: Repo = try await c.call("repo.add", .obj(["path": .string(repoPath)]), as: Repo.self)
    let first = try await c.call("worktree.create", .obj(["repoId": .string(repo.id), "branch": "first"]))
    #expect(first["setupNeedsTrust"]?.bool == true)
    let shown = try await c.call("scripts.list", .obj(["worktreeId": first["id"] ?? .null]))
    #expect(shown["file"]?.string?.hasSuffix("/.conductor/settings.toml") == true && shown["setup"]?.string?.contains("SETUP_RAN") == true)
    _ = try await trustAsShown(c, first["id"] ?? .null)

    let second = try await c.call("worktree.create", .obj(["repoId": .string(repo.id), "branch": "second"]))
    #expect(second["setupSession"] != nil && second["setupNeedsTrust"] == nil)
    let marker = (second["path"]?.string ?? "") + "/SETUP_RAN"
    #expect(try await waitFor(10) { FileManager.default.fileExists(atPath: marker) })
    let line = (FileManager.default.contents(atPath: marker)).map { String(decoding: $0, as: UTF8.self) } ?? ""
    let parts = line.trimmingCharacters(in: .whitespacesAndNewlines).split(separator: "|", omittingEmptySubsequences: false)
    let real = realpath(repoPath, nil).map { p in defer { free(p) }; return String(cString: p) } ?? repoPath   // /private/tmp, as the daemon keeps it
    #expect(parts.count == 2 && parts[0] == Substring(real) && Int(parts[1]) != nil, "\(line)")
}
