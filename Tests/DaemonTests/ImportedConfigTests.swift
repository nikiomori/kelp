private func script(_ c: RepoConfig?, _ name: String) -> String? { c?.scripts.first { $0.name == name }?.command }

/// Conductor's file: setup, the default run among several, args and a folder, teardown as `archive`, a multi-line script.
@Test func conductorsSettingsBecomeTheProjectsCommands() {
    let c = ImportedConfig.conductorTOML("""
    # Conductor
    [scripts]
    setup = \"\"\"
    pnpm install --frozen-lockfile
    cp "$CONDUCTOR_ROOT_PATH/.env" .
    \"\"\"
    archive = 'docker compose down'

    [scripts.run.dev]
    command = "pnpm dev"
    default = true

    [scripts.run.storybook]
    command = "pnpm"
    args = ["storybook", "--port", "6006"]
    options.cwd = "apps/web"
    """, "/Users/me/app")
    #expect(c?.setup == "pnpm install --frozen-lockfile\ncp \"$CONDUCTOR_ROOT_PATH/.env\" .")
    #expect(script(c, "run") == "pnpm dev")
    #expect(script(c, "storybook") == "cd 'apps/web' && pnpm 'storybook' '--port' '6006'")
    #expect(script(c, "archive") == "docker compose down")
    #expect(c?.prelude.hasPrefix("export CONDUCTOR_ROOT_PATH='/Users/me/app' ") == true)

    let legacy = ImportedConfig.conductorJSON(#"{"scripts": {"setup": "pnpm i", "run": "pnpm dev:web"}, "name": "x"}"#, "/r")
    #expect(legacy?.setup == "pnpm i" && script(legacy, "run") == "pnpm dev:web")
}

